"""Pick each baseline's parameter (lowest final regret = highest total reward on the tuning seeds) and write
configs/tuned.json and paper/tables/tab_tuning_<data>.tex. Warns when the winner is at the edge of its grid."""
import json
import os
import numpy as np
import _path  # noqa: F401
from nbplus.runner import ROOT, TUNED, load_results

CHECK = r"$\checkmark$"

if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "results"))
    res = ap.parse_args().results
    tuned = json.load(open(TUNED)) if os.path.exists(TUNED) else {}
    for data in sorted(os.listdir(res)) if os.path.isdir(res) else []:
        if not os.path.isdir(os.path.join(res, data)):  # skip REPORT.md and other files
            continue
        names = [n for n in os.listdir(os.path.join(res, data)) if n.startswith("tune_")]
        if not names:
            continue
        table = {}
        for n in names:
            _, algo, val = n.split("_", 2)
            r = load_results(res, data, n)
            if r:
                table.setdefault(algo, []).append((float(val), np.mean([v["rew"].sum() / v["T"] for v in r.values()]), len(r)))
        lines = ["% generated by scripts/select_tuned.py", r"\begin{tabular}{llcc}", r"\toprule",
                 r"Method & Parameter & Mean reward per round & Selected \\", r"\midrule"]
        names_tex = {"banditron": r"Banditron ($\gamma$)", "linucb": r"LinUCB ($\alpha$)", "lints": r"CTS ($v$)"}
        for algo, rows in sorted(table.items()):
            rows.sort()
            best = max(rows, key=lambda r: r[1])
            tuned.setdefault(data, {})[algo] = best[0]
            edge = best[0] in (rows[0][0], rows[-1][0])
            print(f"{data:10s} {algo:10s} -> {best[0]}  ({len(rows)} values, seeds per value {[r[2] for r in rows]})"
                  + ("   WARNING: at the edge of the grid, extend it" if edge else ""))
            for i, (v, acc, _) in enumerate(rows):
                lines.append(f"{names_tex.get(algo, algo) if i == 0 else ''} & {v:g} & {acc:.4f} & "
                             f"{CHECK if v == best[0] else ''} " + r"\\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        os.makedirs(os.path.join(ROOT, "paper", "tables"), exist_ok=True)
        with open(os.path.join(ROOT, "paper", "tables", f"tab_tuning_{data}.tex"), "w") as f:
            f.write("\n".join(lines) + "\n")
    with open(TUNED, "w") as f:
        json.dump(tuned, f, indent=1)
    print(f"wrote {TUNED}")
